# --- THE DIGITAL EXHIBIT VAULT ---

class Evidence(models.Model):
    """
    Core record for digital evidence. 
    Handles secure ingestion, hashing, and metadata mapping with strict file-lock management.
    """
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    title = models.CharField(max_length=255)
    description = models.TextField(blank=True)
    
    # --- STORAGE & SECURITY VALIDATION ---
    # Updated with Help Text Guide for the Admin Panel
    file_upload = models.FileField(
        upload_to='exhibits/%Y/%m/%d/', 
        null=True, 
        blank=True,
        validators=[validate_file_size, validate_forensic_file_type],
        help_text=mark_safe(
            '<div style="margin-top: 10px; color: #666; font-size: 0.85rem;">'
            '<strong>ACCEPTED FORENSIC FORMATS:</strong><br>'
            '• <b>Images:</b> .jpg, .png, .tiff, .raw<br>'
            '• <b>Video/Audio:</b> .mp4, .mov, .wav, .mp3<br>'
            '• <b>Documents:</b> .pdf, .docx, .txt, .csv<br>'
            '• <b>Archives:</b> .zip, .iso, .e01, .ad1'
            '</div>'
        )
    )
    
    original_hash = models.CharField(max_length=64, blank=True, null=True, editable=False)
    mime_type = models.CharField(max_length=100, blank=True, null=True, editable=False)
    
    # --- LIVE INTEGRITY MONITORING ---
    INTEGRITY_CHOICES = [
        ('PENDING', 'Not Yet Verified'),
        ('INTACT', 'Integrity Verified (Match)'),
        ('FAILED', 'TAMPERED OR CORRUPTED (Mismatch)'),
    ]
    
    integrity_status = models.CharField(
        max_length=20, 
        choices=INTEGRITY_CHOICES, 
        default='PENDING'
    )
    last_verified_at = models.DateTimeField(null=True, blank=True)

    # DETAILED FORENSIC LOGGING
    tamper_details = models.TextField(
        blank=True, 
        null=True, 
        editable=False,
        help_text="Detailed forensic alerts regarding file modifications generated by the analysis engine."
    )

    # --- FORENSIC METADATA ---
    captured_at = models.CharField(max_length=100, blank=True, null=True, editable=False)
    device_info = models.CharField(max_length=255, blank=True, null=True, editable=False)
    location_data = models.CharField(max_length=255, blank=True, null=True, editable=False)
    duration = models.CharField(max_length=50, blank=True, null=True, editable=False)
    resolution = models.CharField(max_length=50, blank=True, null=True, editable=False)
    
    uploaded_by = models.ForeignKey(User, on_delete=models.SET_NULL, null=True, blank=True)
    uploaded_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name_plural = "Digital Evidence Exhibits"
        indexes = [
            models.Index(fields=['original_hash'], name='hash_idx'),
            models.Index(fields=['-uploaded_at'], name='upload_date_idx'),
            models.Index(fields=['integrity_status'], name='status_idx'),
        ]

    def save(self, *args, **kwargs):
        """
        Saves the record and ensures the file is released immediately after hashing.
        """
        if self.file_upload and not self.original_hash:
            # 1. GENERATE HASH (Using chunks to avoid memory locks)
            sha256_hash = hashlib.sha256()
            
            for chunk in self.file_upload.chunks():
                sha256_hash.update(chunk)
            
            temp_hash = sha256_hash.hexdigest()

            # 2. DUPLICATE DETECTION
            duplicate = Evidence.objects.filter(original_hash=temp_hash).exclude(id=self.id).first()
            if duplicate:
                raise ValidationError(
                    f"Forensic Duplicate Detected: This exact file already exists as '{duplicate.title}'."
                )

            self.original_hash = temp_hash
            
            # 3. EXTRACT MIME TYPE (Safely closing the buffer via try/finally)
            try:
                self.file_upload.seek(0)
                header_data = self.file_upload.read(2048)
                self.mime_type = magic.from_buffer(header_data, mime=True)
            finally:
                self.file_upload.seek(0)

        super().save(*args, **kwargs)

    def check_integrity(self):
        """
        Manually re-verifies the file.
        """
        try:
            current_hash = calculate_sha256(self.file_upload)
            
            self.integrity_status = 'INTACT' if current_hash == self.original_hash else 'FAILED'
            self.last_verified_at = timezone.now()
            self.save(update_fields=['integrity_status', 'last_verified_at'])

            AuditLog.objects.create(
                evidence=self,
                user=None, 
                action='VERIFY',
                recorded_hash=current_hash,
                details=f"Manual Integrity Check. Result: {self.integrity_status}"
            )
            return self.integrity_status
        except Exception as e:
            return f"Verification Error: {str(e)}"

    def __str__(self):
        return f"{self.title} ({self.id})"

# --- THE AUDIT TRAIL ---

class AuditLog(models.Model):
    ACTION_CHOICES = [
        ('UPLOAD', 'Evidence Uploaded'),
        ('VIEW', 'Evidence Viewed'),
        ('DOWNLOAD', 'Evidence Downloaded'),
        ('VERIFY', 'Hash Re-verified'),
        ('DELETE', 'Evidence Deleted'),
        ('FORENSIC_EXTRACT', 'Metadata Extracted'),
    ]

    evidence = models.ForeignKey(Evidence, on_delete=models.SET_NULL, null=True, related_name='audit_logs')
    user = models.ForeignKey(User, on_delete=models.SET_NULL, null=True)
    action = models.CharField(max_length=20, choices=ACTION_CHOICES)
    ip_address = models.GenericIPAddressField(null=True, blank=True)
    timestamp = models.DateTimeField(default=timezone.now)
    details = models.TextField(blank=True, null=True)
    recorded_hash = models.CharField(max_length=64, blank=True)

    class Meta:
        ordering = ['-timestamp']

