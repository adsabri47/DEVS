# --- AUTOMATIC SIGNAL RECEIVER ---

@receiver(post_save, sender=Evidence)
def auto_verify_and_extract(sender, instance, created, **kwargs):
    """
    Post-save forensic processing. 
    """
    if created and instance.file_upload:
        try:
            update_data = {}
            file_path = instance.file_upload.path

            if instance.mime_type and 'image' in instance.mime_type:
                meta = get_exif_metadata(instance.file_upload)
                update_data = {
                    'captured_at': meta.get('date_time'),
                    'device_info': meta.get('device'),
                    'location_data': meta.get('gps')
                }
            
            elif instance.mime_type and ('video' in instance.mime_type or 'audio' in instance.mime_type):
                media = get_media_metadata(file_path)
                update_data = {
                    'duration': media.get('duration'),
                    'resolution': media.get('resolution')
                }

            if update_data:
                Evidence.objects.filter(id=instance.id).update(**update_data)

            AuditLog.objects.create(
                evidence=instance,
                user=instance.uploaded_by,
                action='UPLOAD',
                recorded_hash=instance.original_hash,
                details=f"Automatic Forensic Ingestion. Hash verified: {instance.original_hash}"
            )

        except Exception as e:
            print(f"Automated Forensic Error: {e}")